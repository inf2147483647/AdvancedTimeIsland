## 周期性倒计时
与“多倒计时 / 正计时”不同，周期性倒计时不是倒计时到某个固定时刻，而是按**固定周期反复推算下一次目标时间**：
- 支持周期：小时 / 日 / 周 / 月 / 年。
- 到点后自动进入下一周期，无需手动改目标时间。
- 适合每节课、每周升旗、每月例会等周期性剩余时间场景。
- 文案格式变量与多倒计时一致（见上方人类部分的格式化变量）。

## 更多主界面组件

### 节日 / 节气 / 星座 / 生肖 / 宜忌
