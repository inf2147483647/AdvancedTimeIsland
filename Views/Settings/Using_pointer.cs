### 4.3 交互行为

- **点击穿透**：悬浮窗对鼠标点击透明，点击会落到下方窗口；同时临时关闭拖拽。
- **指针淡化**：指针进入悬浮窗区域时整体淡化到 5%，移出恢复。
- **指针淡化反转**：开启后改为「指针在窗外时淡化，移入窗口恢复」。
- **贴边自动隐藏**：拖到屏幕边缘（小于 8px）时滑出屏幕，只保留约 6px 可见条；指针移入可见条滑回。
- **贴边隐藏延迟**：0 ~ 60 秒，默认 3 秒，0 表示立即隐藏。

### 4.4 窗口与高级

- **窗口层级**：置底（默认，不遮挡其他窗口）或置顶（不推荐）。
- **层级重设频率**：窗口层级变化时 / 前台窗口变化时 / 每 50ms（默认）/ 每 2s / 每 1ms（不推荐，开销与闪烁风险高）。
- **复位窗口**：把悬浮窗强制放回默认位置（100,100）并退出贴边停靠状态，用于窗口被拖到屏幕外或找不到；立即生效，无需重启。
- **隐藏悬浮窗**：跟随主界面隐藏规则（默认）/ 基础模式（复用上课时、最大化、全屏三个开关）/ 高级模式（复用主界面隐藏规则集）/ 从不隐藏。

### 4.5 反拦截与截图

- **随机窗口名**：窗口标题改为随机字符串，防止学校弹窗拦截工具按标题识别。
- **随机窗口名增强**：每 1 秒重新生成一次标题，仅在上一项开启时生效。
- **阻止截图**：其他应用无法截取悬浮窗内容，录屏时也不会出现。Windows 10 2004 及以上为完全排除，更低版本回退为黑色遮挡。
- **独立进程模式**：由 `AdvancedTimeIslandFloatSchedule.exe` 渲染悬浮窗，防拦截能力更强，且不受 ClassIsland 主程序卡顿影响。仅 Windows 可用。

独立进程模式附加选项：

| 设置项 | 说明 |
| --- | --- |
| 启用独立进程模式 | 切换后即时生效 |
| 随机进程名 | 以随机命名的稳定副本启动子进程，进一步规避按进程名拦截；可能触发杀软误报 |
| 重新启动子进程 | 立即终止并按当前设置重启，约 1~2 秒恢复 |
| 单实例保护 | 已有子进程时新进程直接退出，由插件接管连接 |
| 跟随启停 | ClassIsland 关闭后子进程一并关闭；关闭则冻结显示最后课表并在宿主重启后自动重连 |

> [!note]
> 若子进程被安全软件拦截、副本无法写入，插件会回退到进程内渲染并提示原因。可将 `%LOCALAPPDATA%\AdvancedTimeIsland\FloatSchedule\` 加入白名单，或关闭独立进程模式。

