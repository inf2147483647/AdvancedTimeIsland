### 3.2 文本样式通则

所有组件的字体项含义一致：

- **文本大小**：关闭右侧启用开关时使用 ClassIsland 正文字体大小；开启后取值范围 6 ~ 72。不建议超过 40。
- **文本颜色**：颜色选择器控制；关闭启用开关时随主题。
- **字体样式**：可选择系统已安装字体，实际效果取决于字体兼容度；关闭后使用宿主默认字体。
- **字体字重**：需所选字体支持对应字重。
- 各段文案（文案 1/2/3/4、名称、时间）均可单独设置，互不影响。

### 3.3 日期显示

- **显示星期**：控制星期部分显隐。
- **内容组合**：日期-星期（2026.7.29 周三）或星期-日期（周三 2026.7.29）。
- **日期分隔符**：`-`、`/`、`.` 或纯文本。
- 日期与星期可分别设置字体大小、颜色、字体与字重。

### 3.4 多倒计时

解决了原版倒计时可能显示负数、秒 60、分 60、小时 24 的问题。

**文案顺序**：文案 1 → 倒计时名称 → 文案 3 → 剩余时间 → 文案 4。
示例：`距离 新倒计时 还有 1天14小时5分钟14秒191毫秒 请注意。`

默认文案 1 为「距离」、文案 3 为「还有」，剩余时间默认格式为 `%d天%h小时%m分钟%s秒`。

**格式化变量**（用于组件里的时间文本，与「时间计算器」的减数格式化规则不同）：

| 变量 | 含义 |
| --- | --- |
| `%D` / `%H` / `%M` / `%S` / `%X` | 总天数 / 总小时 / 总分钟 / 总秒 / 总毫秒 |
| `%d` / `%h` / `%m` / `%s` / `%x` | 天 / 小时 / 分钟 / 秒 / 毫秒（分秒毫秒补零） |
| `%L` / `%P` / `%p` | 剩余百分比 / 已过百分比 / 已过百分比（两位小数） |
| `%yy` / `%YY` | 总年 / 总年（两位） |
| `%mo` / `%MO` | 总月 / 总月（两位） |

**主要选项**：

- **差一矫正**：精度不足时最小单位加一，避免出现 60 秒、60 分、24 小时；默认开启。
- **时间基准**：插件偏移后的服务器时间（默认）、原始服务器时间、ClassIsland 时间。
- **简化模式**：只显示倒计时名称与剩余时间。
- **进度显示**：两个独立复选框「进度条」「进度环」，可同时勾选；各自的颜色可单独自定义。
- **仅计在校时长**：开启后剩余时间只统计在校秒数（排除周末、节假日、寒暑假及课表窗口外时段），进度条/进度环也同步改用总在校时长作为基准。
- **到达通知**：可为每个倒计时单独开启；可设置通知标题、内容、主界面遮罩文案与显示时长（1~60 秒）、覆盖层文案与显示时长（1~60 秒）。
- **倒计时列表**：增删倒计时、设置名称、目标时间、通知与「仅计在校时长」。

> [!note]
> 旧版本「进度条显示」下拉框（不显示 / 进度条 / 进度环 / 进度条和进度环）已替换为上述两个复选框。旧配置无需迁移，勾选状态与原选择一一对应；依赖旧下拉框的截图或教程会与当前界面不一致。

### 3.5 正向计时器

与多倒计时相比：

- 没有倒计时列表，只有一个起点时间。
- 没有进度条 / 进度环与「仅计在校时长」。
- 文案顺序为：文案 1 → 名称 → 文案 3 → 已过时间 → 文案 4，默认文案 3 为「已过」。
- 格式化变量、时间基准、简化模式与多倒计时一致。

### 3.6 周期性倒计时

周期性倒计时不是倒计时到某个固定时刻，而是按固定周期反复推算下一次目标时间：

- 支持周期：小时 / 日 / 周 / 月 / 年。
- 到点后自动进入下一周期，无需手动修改目标时间；也可显示周期性进度。
- 每周需选择星期，每月需选择日，每年需选择月与日。
- 文案、格式化变量、时间基准、进度显示、简化模式与多倒计时一致。

> [!caution]
> 周期性倒计时首次使用时会弹出说明，需要确认后才启用。

### 3.7 农历多倒计时

与多倒计时类似，但目标日期为农历：

- 可设置农历年、月、日、是否闰月与时、分、秒。
- 支持到达通知、进度显示、简化模式、时间基准。
- 与多倒计时一样按列表管理多个农历倒计时。

> [!caution]
> 在输入完参照公历后，必须点击转换为农历才会生效。

### 3.8 今日周数

- **今日周数（年）**：显示当前日期属于本年的第几周；一周始自周日，第一个完整周记为第 1 周。
- **今日周数（学期）**：以 ClassIsland 档案中的学期开始日作为第一周第一天计算学期周数。
- **本周单双**：同样以学期开始日为第一周，显示当前学期周是「单周」还是「双周」。

三者都支持时间基准、字体样式与自定义显示内容。

### 3.9 总在校时间统计

主界面组件展示五段可独立开关与设置样式的文案：概要、累计在校时长、进度百分比、剩余天数、剩余时长；可显示进度条 / 进度环、分段分隔线，小时数可选择是否小数化。

数据来源在「在校时间统计」设置页配置：

- **学期区间**：自动读取 ClassIsland 学期开始日与学期总周数，也可手动指定开始日 / 结束日。
- **每日在校时长**：每天计入的小时数。
- **排除规则**：排除周六、排除周日、排除法定节假日、调休补班日计为在校日（优先于周末排除）、排除寒暑假区间、应用自定义日期（强制计入 / 强制排除）。
- **寒暑假区间**：可添加多个假期的名称、开始与结束日期。
- **自定义日期**：按日期强制计入或强制排除，并可为当天命名。
- **法定节假日与调休**：内置数据，可添加条目、从网络更新或恢复内置数据。
- **分段统计**：按选择的维度查看各分段在校情况。

设置页顶部有「刷新统计」按钮，修改规则后点击可立即重算。

### 3.10 农历相关展示

- **星座 / 下个星座倒计时**：显示当前星座，以及距下一个星座开始的时间。
- **节气 / 下个节气倒计时**：显示二十四节气，以及距下一个节气的时间。
- **今日宜忌 / 明日宜忌**：展示当日 / 次日黄历宜忌，可切换显示模式与字体样式。
- **生肖**：显示当前农历生肖。
- **农历日期**：显示今日农历日期（含闰月标识），如「农历 丙午年正月十五」。
- **节日 / 下个节日倒计时**：显示传统节日；节日组件可分别开关国际节日、中国传统节日与红色节日，并支持联网更新与手动编辑节日数据。

以上均基于农历（lunar）库计算，需要先在「管理启用的功能」中开启对应功能并重启 ClassIsland。

### 3.11 地方时 / 区时 / 日出日落

- **地方时**：按经度推算的本地太阳时，可在组件里单独设置经度。
- **区时**：按指定时区显示时间，组件内可单独选择时区。
- **日出日落**：按经度、纬度与时区计算当天日出 / 日落时刻，可调整精度与文本样式。

### 3.12 实验性组件

开启「插件设置 → 实验性功能」并重启后，额外注册：

- **七段数码管时钟（ATI）**：以七段数码管样式显示当前时间，支持字体与发光样式设置。
- **实时主界面刷新率（调试）（ATI）**：显示当前 / 最高 / 平均 FPS，用于排查动画性能。

