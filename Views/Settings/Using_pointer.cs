### 1.6 常见问题

**组件显示的时间与 ClassIsland 不一致？**
检查组件的「时间基准」：默认使用插件偏移后的服务器时间，与 ClassIsland 时间相互独立。可在「通用设置」里调整「插件时间偏移」。

**进度条 / 进度环不显示？**
在组件设置里分别勾选「进度条」「进度环」；两者都不勾选即不显示进度。旧版的「进度条显示」下拉框已移除。

**修改了功能开关但组件或触发器没出现？**
除「小工具」外，修改「管理启用的功能」或「实验性功能」后需要点击「应用并重启」，重启 ClassIsland 才会重新注册页面、组件、触发器与规则。

**区时类自动化结果不对？**
确认设备时区下拉框选中的是合法时区（如「China Standard Time」）。旧版本曾使用 `UTC+8` 这类非法时区 Id，升级后请重新检查设置。

**悬浮窗找不到了？**
到「时间表悬浮窗 → 窗口与高级」点击「复位窗口」。若开启了贴边隐藏，窗口可能藏在屏幕边缘的可见条里。

**32 位 ClassIsland 无法同步时间？**
时间同步依赖 64 位进程。32 位宿主下相关设置会隐藏并显示提示，组件仍可使用系统时间加插件偏移。

**设置界面的工具页、帧率折线、汉服指南不见了？**
这三项默认关闭，请到「插件设置 → 管理启用的功能」中开启；「帧率折线」和「汉服指南」还需先开启「实验性功能」。

## 二、自动化

自动化在 ClassIsland 的「自动化」设置中配置，由触发器、规则与行动组成。ATI 注册的触发器、规则与行动可直接在原生自动化编辑器里添加。

### 2.1 时间基准

- 触发器与规则默认使用**插件时间**：NTP 校准后的服务器时间加「插件时间偏移」，与 ClassIsland 自身的时间偏移独立。
- 涉及地方时、区时的触发器与规则按各自经度 / 时区换算。
- 农历类触发器与规则按农历日期换算。
- 组件中的「时间基准」选项只影响组件显示，不影响自动化判定。

### 2.2 触发器（到点触发）

基础触发器（始终注册）：

| 触发器 | 说明 |
| --- | --- |
| 精确时间是 | 在指定的绝对时刻触发一次 |
| 每年 / 每月 / 每周 / 每天 / 每小时 / 每分钟 | 按周期在指定时刻触发 |
| 绝对时间 | 到达指定 Unix 时间戳时触发（单位：秒） |

开启「实验性功能」后额外注册「时间范围间隔触发」系列，用于在时间范围内按间隔重复触发：

| 触发器 | 说明 |
| --- | --- |
| 精确时间范围间隔触发 | 在起止时刻之间按间隔重复触发 |
| 每年 / 每月 / 每天 / 每小时 / 每分钟时间范围间隔触发 | 在对应周期的时间范围内按间隔重复触发 |
| 绝对时间戳范围间隔触发 | 在 Unix 时间戳区间内按间隔重复触发 |

开启对应功能后额外注册：

- **农历**：农历精确时间、农历每年、农历每月、农历年倒数第 n 天，以及农历精确 / 每年 / 每月时间范围间隔触发。
- **地方时**：地方时精确时间、地方时每年 / 每月 / 每周 / 每天 / 每小时 / 每分钟，以及除每周外各周期的间隔触发。
- **区时**：区时精确时间、区时每年 / 每月 / 每周 / 每天 / 每小时，以及除每周外各周期的间隔触发。

### 2.3 规则（时间段 / 条件）

| 规则 | 说明 |
| --- | --- |
| 精确时间在范围 | 当前时刻落在两个绝对时刻之间 |
| 每年 / 每月 / 每周 / 每天 / 每小时 / 每分钟时间范围 | 按对应周期判断当前是否处于设定区间 |
| 在指定时间范围内 | 在绝对起止时间之间 |
| 绝对时间范围 | 当前 Unix 时间戳落在指定区间 |
| 农历精确时间范围 / 农历每年时间范围 / 农历每月时间范围 | 按农历判断 |
| 地方时精确 / 每年 / 每月 / 每周 / 每天 / 每小时 / 每分钟时间范围 | 按地方时判断 |
| 区时精确 / 每年 / 每月 / 每天 / 每小时 / 每周时间范围 | 按区时判断 |
| 当前星座是 / 当前节气是 / 当前生肖是 / 当前节日是 | 按当前农历状态判断，需要开启对应功能 |

时间范围类规则的起止时间采用时 / 分 / 秒独立下拉分量，结束端点统一按「起点含、终点不含」处理。

> [!note]
> 「每周时间范围」表示从「开始星期 + 开始时间」到「结束星期 + 结束时间」的一整段连续区间，而不是每天重复的时段。例如「周一 08:00 → 周五 17:00」覆盖周一 08:00 至周五 17:00 全程（夜间同样命中）。若需要旧的「每天 08:00–17:00」语义，请改用「每天时间范围」并配合星期几条件。
>
> 结束时间早于开始时间时自动顺延：同一天内顺延到次日，跨星期则顺延到下一周；起止完全相同视为零长区间，永不命中。

### 2.4 行动

| 行动 | 说明 |
| --- | --- |
| 同步 ClassIsland 时间 | 让宿主 ClassIsland 重新校准自身时间 |
| 同步 AdvancedTimeIsland 插件时间 | 让插件立即执行一次 NTP 时间同步（超时 10 秒） |
| 设置悬浮时间表开关 | 把「启用悬浮时间表」设为行动中配置的状态 |

