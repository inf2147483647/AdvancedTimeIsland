## 二、精准尺码测量与放量标准
汉服尺码不以S/M/L为核心依据，需按身体数据选择，男女同款统一按数据匹配，无性别尺码差异。

### （一）必测身体数据
准备软尺，自然站立测量，记录以下5项核心数据：
1. **身高**：赤脚站直，从头顶到地面的垂直高度，决定衣长、通袖长的基础。
2. **净胸围**：胸部最丰满处水平环绕一圈，正常呼吸时测量，是选码的核心依据。
3. **肩宽**：两侧肩峰点之间的直线距离，影响肩部贴合度。
4. **通袖长（净尺寸）**：双臂水平平伸，从左手指尖到右手指尖的总长度，约等于自身身高。
5. **腰围**：腰部最细处环绕一圈，束腰款式需重点参考。

### （二）核心尺寸计算公式
#### 1. 通袖长选择
根据形制正式程度选择，日常款不宜过长，避免影响行动：
- 日常便服（窄袖/直袖/弓袋袖）：**身高 + 0~15cm**，手臂下垂时袖口过指尖2-3cm
- 常规常服（琵琶袖/中袖）：**身高 + 30~45cm**，回腕款，可将手收进袖口
- 礼服款（大袖/广袖）：**身高 + 50cm以上**，回肘款，氛围感强

#### 2. 衣长参考
- 短衫/半臂：衣长到腰下5cm左右，刚好盖住腰线
- 直裰/短款道袍：衣长过膝10~15cm
- 长款道袍/圆领袍/直身：衣长到脚踝上方2~3cm，不拖地为宜
- 褙子/披风：短款到胯部，中长款到膝盖，长款到脚踝

### （三）放量标准（胸围）
汉服讲究宽松垂坠，需在净胸围基础上加放量，不同场景放量不同：
