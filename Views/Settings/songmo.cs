宋抹是宋代女子所穿的抹胸，属古代亵衣的一种，亦为汉服组成部分。其以帛或布制成，形制似宽长巾，既有短小款式，亦有较长大者可著于外。颜色有白、粉等，用于固定胸部并防风寒，各阶层女性普遍使用，现代因汉服复兴而称其为""宋抹""。

