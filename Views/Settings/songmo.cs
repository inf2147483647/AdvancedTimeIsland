## 概念

宋抹指宋代女子所穿的抹胸，亦称抹胸、抹肚，是女性的贴身内衣。其特点是不施于背，仅覆于胸，类似于唐代的诃子。主要功能在于固定胸部。其材质多为棉、布或丝绸，常绣有精美图案。北宋程颐伯祖母曾有一件珠子装抹胸，价值不菲。抹胸外罩褙子是宋代从后妃、闺秀到乐伎、平民女性中广泛流行的典型装束，呈现出内衣外穿的风尚。

""抹胸""一词正式见于南唐后主李煜的词《谢新恩》：""双鬓不整云憔悴，泪沾红抹胸。何处相思苦？纱窗醉梦中""。传说抹胸是唐代杨贵妃首创，即认为抹胸起源于诃子，《唐宋遗事》载：""贵妃日与安禄山嬉游，一日醉舞，无礼尤甚，引手抓伤妃胸乳间，妃泣曰：吾私汝之过也。虑帝见痕，以金为诃子遮之。后宫中皆效焉""。后世多以为""抹胸""即""肚兜""，实际上是误读。肚兜是以方尺之布为之，用以防风，且男女皆可穿。而抹胸（宋抹）为女性专用，主要用于固定胸部。明清时期，因理学盛行等因素，肚兜逐渐取代抹胸成为主流内衣，以致清末民国时人们将二者混为一谈。

抹胸的形制多样，并非均为裹在胸部的圈。例如南宋黄昇墓出土的抹胸实物即以素绢制成，长55厘米，宽40厘米，呈长方形，上端及腰间缀有绢带用于系缚。历史上并无""宋抹""一词，而系随着近年来汉服复兴，宋代形制的抹胸又为人所热爱，且其与现代抹胸有显著区别，因此人们渐称之为""宋抹""。正如""唐诗""作为""诗""中翘楚而为人们津津乐道一样。""宋抹""常与""褙子""并提，作为宋代女子服饰的代表。
## 形制
出土的宋抹有两种，最具代表性的是花山宋墓出土之抹胸。
宋抹形制似宽长巾，有短小和较长两种，颜色多为浅色调，如白、粉等，以帛或布制成。宋抹具有顺褶和收省两种形式。抹胸穿着后上可覆乳、下可遮肚，整个胸腹全被掩住，因而又称抹肚。
2003年出土于南京花山宋墓的抹胸，呈长方形，竖长50厘米，横宽116厘米，上部中间大有褶皱，两边系绳，带长51厘米，为绢质，轻薄坚韧，表面光泽柔和。经过七百多年，抹胸大部分颜色褪去，呈灰黄色，其实上面曾染了红绿黄褚等各种颜色。宋人的审美观崇尚自然淡雅，这件抹胸从色调到图案呈现出的便是简约清雅的风格，衣料表面只是用印花工艺装饰出细碎的黑色菱形纹，并填以柿蒂小花相错排列，给人以古朴素雅之感。虽然外表不算“花哨”，但古人对衣物穿着的舒适度却很是讲究，比如抹胸四边均以印花绢贴边，贴身穿着很是柔软舒适。此外，抹胸左右两侧还分别设有一根系带，在穿戴时起到固定的作用。
目前出土年代最早的抹胸实物为福建福州南宋黄昇墓的抹胸，以素绢为之，长55厘米，宽40厘米，上端及腰间各缀绢带两条。河南禹县白沙宋墓壁画中的妇女形象也内围抹胸，形制与黄昇墓出土物略有不同。
同样是“内衣”，现代人与宋朝人的穿法却有很大不同。在宋代，抹胸作为“女士内衣”并不是完全藏在外衣里不能见人的。据文献记载，宋代女子无论平民还是贵妇都喜欢内穿抹胸，外穿一件对襟窄袖的褙子，而且衣襟大都没有纽扣或绳带系连，呈自然敞开式，因此里面的抹胸会不时显现出来，隐约露出内衣之美。
明代抹胸仍沿宋抹形制。围在妇女胸前的围裹，名为“腰子”，是胸前胸后都有的，即使天寒时也有上身只服此者，露出肩臂和乳上部。面料主要为质地轻薄的纱、绫等。根据季节不同有冬季装和夏季装。当代抹胸即是以花山宋墓出土的这件抹胸为原型，并有所创新。
## 发展历程
抹胸起源于唐代的“诃子”，传说为杨贵妃所创。 
“抹胸”一词最早见于南唐后主李煜的词作。
至宋代，抹胸逐渐发展为外穿衣着，广泛流行于各阶层女性中。宋人对抹胸极讲究，材质多为棉、布或丝绸，上面绣有精美的图案。“抹胸+褙子”是宋朝女性的典型装束。有出土实物和图像证据，如黄昇墓出土的抹胸实物和河南禹县白沙墓的壁画。
因汉服复兴，以宋抹为灵感的新中式吊带成为潜在流行款式。
## 穿着方式与社会普及
宋抹最核心的穿着方式是“抹胸+褙子”的组合。宋朝女性习惯内穿抹胸，外套一件褙子，褙子双襟自然垂下，不系带不扣纽，任其敞开，因此抹胸略为外露。
这种着装广泛流行于几乎所有社会阶层。南宋萧照《中兴瑞应图》上的宋廷嫔妃与宫女，南宋刘宗古《瑶台步月图》中的大家闺秀，南宋佚名《歌乐图卷》里的宫廷乐伎，以及《杂剧人物图》中的市井伶人均如此穿着。南宋李嵩《骷髅幻戏图》与南宋佚名《荷亭儿戏图》中的平民女性也身穿“抹胸+褙子”。《宋史·舆服志》载后妃常服包括背子，《武林旧事》记公主嫁妆有“真珠大衣、背子”，《东京梦华录》描述媒人“着紫背子”，《西湖老人繁胜录》载酒库歌伎“都着红背子、特髻” 。
在炎热的夏天，褙子往往用半透明的薄纱罗制成。学者孟晖在《中原历代女子服饰史稿》中指出，“内衣外穿，袒露颈、胸，实在是有宋一代的平常风气” 。南宋朱熹所定“家礼”中，背子亦是女性礼服之一。
